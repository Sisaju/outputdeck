def translate(source, language='de', **values):
    if language == 'en' and source.endswith(' fehlt. Bitte alsa-utils und pulseaudio-utils installieren.'):
        return source.split(' fehlt.')[0] + ' is missing. Please install alsa-utils and pulseaudio-utils.'
    if language == 'en' and source.startswith('Systemeinstellungen konnten nicht geöffnet werden:'):
        return 'Could not open system settings:' + source.split(':', 1)[1]
    phrase = EN.get(source, source) if language == 'en' else source
    return phrase.format(**values) if values else phrase


def saved_language():
    config = configparser.ConfigParser()
    config_root = Path(os.environ.get('XDG_CONFIG_HOME', Path.home() / '.config'))
    path = config_root / 'SoundBlasterControl/SoundBlasterControl.conf'
    config.read(path)
    language = config.get('General', 'language', fallback='de')
    return language if language in ('de', 'en') else 'de'
